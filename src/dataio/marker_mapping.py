def default_class_mapping_path() -> str:
    return os.environ.get(
        "FCM_ML_CLASS_MAPPING_PATH",
        str(Path(__file__).with_name("class_mappings") / "datasets_class_mappings.json"),
    )


def load_class_list_for_dataset(
    dataset_key: str,
    *,
    mapping_path: Optional[str] = None,
) -> tuple[List[str], List[int]]:
    """
    从预先生成的映射文件加载某个数据集的 CLASS_LIST 与 CLASS_NUMBER。

    Args:
        dataset_key: 通常由 *_dataset_split.xlsx 推导出来的 key
        mapping_path: 映射 JSON 路径；默认使用环境变量 FCM_ML_CLASS_MAPPING_PATH，
                      若未设置则使用安装包内的 class_mappings/datasets_class_mappings.json。
    """
    if mapping_path is None:
        mapping_path = default_class_mapping_path()
    info = load_dataset_class_info(mapping_path, dataset_key=dataset_key)
    return info.class_list, info.class_counts

